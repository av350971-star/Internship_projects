def find_customer(query: str) -> list[dict]:
    """Fuzzy search customers by name, email, phone or id."""
    q = query.lower().strip()
    return [
        c for c in CUSTOMERS
        if q in c["name"].lower() or q in c["email"].lower()
        or q in c["phone"].lower() or q in c["id"].lower() or q in c["city"].lower()
    ]


def orders_of(customer_id: str) -> list[dict]:
    return [o for o in ORDERS if o["customer_id"] == customer_id]


def orders_of_any(customer_ids: list[str]) -> list[dict]:
    return [o for o in ORDERS if o["customer_id"] in customer_ids]


# ---------------------------------------------------------------------------
# Approval store — the consent gate for side-effecting calls
# ---------------------------------------------------------------------------
APPROVALS: dict[str, dict] = {}


def create_approval(action: str, params: dict, summary: str) -> dict:
    appr_id = "APR-" + uuid.uuid4().hex[:8].upper()
    params_copy = dict(params)
    params_copy["approval_id"] = appr_id
    approval = {
        "approval_id": appr_id,
        "action": action,
        "params": params_copy,
        "summary": summary,
        "status": "pending",        # pending -> approved | rejected | used
        "created_at": str(date.today()),
    }
    APPROVALS[approval["approval_id"]] = approval
    return approval


