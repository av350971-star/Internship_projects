def store_summary() -> dict:
    revenue = sum(o["amount"] for o in ORDERS if o["status"] == "delivered")
    return {
        "total_customers": len(CUSTOMERS),
        "total_orders": len(ORDERS),
        "revenue_delivered_orders_inr": revenue,
        "open_tickets": len([t for t in TICKETS if t["status"] in ("open", "in_progress")]),
        "refunds_processed": len(REFUNDS),
    }


def call_tool(name: str, arguments: dict) -> dict:
    """Execute one MCP tool. Returns {"ok": ..., "result"/"error": ...}."""
    if name == "search_customers":
        matches = find_customer(arguments.get("query", ""))
        return {"ok": True, "result": matches}

    if name == "read_orders":
        ids = arguments.get("customer_ids", [])
        return {"ok": True, "result": orders_of_any(ids)}

    if name == "create_support_ticket":
        cid = arguments["customer_id"]
        if not any(c["id"] == cid for c in CUSTOMERS):
            return {"ok": False, "error": f"Unknown customer_id: {cid}"}
        ticket = {
            "id": "TKT-" + str(9000 + len(TICKETS) + 1),
            "customer_id": cid,
            "subject": arguments["subject"],
            "description": arguments["description"],
            "priority": arguments["priority"],
            "status": "open",
            "created_at": str(date.today()),
        }
        TICKETS.append(ticket)
        return {"ok": True, "result": ticket}

    if name == "process_refund":
        # ---- THE CONSENT GATE ----
        approval_id = arguments.get("approval_id", "")
        approval = APPROVALS.get(approval_id)
        if not approval or approval["status"] != "approved":
            return {"ok": False, "error": "Missing or invalid approval. Side-effecting calls require a user-approved, single-use approval_id from POST /api/approvals."}
        order = next((o for o in ORDERS if o["id"] == arguments["order_id"]), None)
        if not order:
            return {"ok": False, "error": f"Unknown order_id: {arguments['order_id']}"}
        if arguments["amount"] <= 0 or arguments["amount"] > order["amount"]:
            return {"ok": False, "error": f"Amount must be between 1 and {order['amount']} INR for this order."}
        approval["status"] = "used"  # single-use: burn the token
        refund = {
            "id": "RFD-" + uuid.uuid4().hex[:6].upper(),
            "order_id": order["id"],
            "customer_id": order["customer_id"],
            "amount": arguments["amount"],
            "reason": arguments["reason"],
            "approval_id": approval_id,
            "processed_at": str(date.today()),
        }
        REFUNDS.append(refund)
        order["status"] = "refunded"
        return {"ok": True, "result": refund}

    return {"ok": False, "error": f"Unknown tool: {name}"}


# ---------------------------------------------------------------------------
# MCP protocol endpoint (JSON-RPC 2.0)
# ---------------------------------------------------------------------------
class McpRequest(BaseModel):
    jsonrpc: str = "2.0"
    id: Any = 1
    method: str
    params: Optional[dict] = None


@app.post("/mcp", dependencies=[Depends(require_api_key)])
def mcp_endpoint(req: McpRequest) -> dict:
    """Minimal MCP server: initialize, tools/list, tools/call, resources, prompts."""
    params = req.params or {}

    if req.method == "initialize":
        return {"jsonrpc": "2.0", "id": req.id, "result": {
            "protocolVersion": "2024-11-05",
            "capabilities": {"tools": {}, "resources": {}, "prompts": {}},
            "serverInfo": {"name": "business-operations-mcp", "version": "1.0.0"},
        }}

    if req.method == "tools/list":
        return {"jsonrpc": "2.0", "id": req.id, "result": {"tools": TOOLS}}

    if req.method == "tools/call":
        outcome = call_tool(params.get("name", ""), params.get("arguments", {}))
        if not outcome["ok"]:
            return {"jsonrpc": "2.0", "id": req.id, "result": {
                "content": [{"type": "text", "text": outcome["error"]}], "isError": True}}
        return {"jsonrpc": "2.0", "id": req.id, "result": {
            "content": [{"type": "text", "text": json.dumps(outcome["result"], indent=2)}], "isError": False}}

    if req.method == "resources/list":
        return {"jsonrpc": "2.0", "id": req.id, "result": {"resources": RESOURCES}}

    if req.method == "resources/read":
        uri = params.get("uri", "")
        if uri == "business://metrics/summary":
            text = json.dumps(store_summary(), indent=2)
        elif uri == "business://policies/refund":
            text = ("Refund policy:\n1. Refunds are allowed within 30 days of delivery.\n"
                    "2. Amount must not exceed the paid amount of the order.\n"
                    "3. Every refund requires explicit human approval via the consent gate.\n"
                    "4. Approved refunds complete in 3-5 business days.")
        else:
            return {"jsonrpc": "2.0", "id": req.id, "result": {
                "contents": [], "isError": True}}
        return {"jsonrpc": "2.0", "id": req.id, "result": {
            "contents": [{"uri": uri, "mimeType": "text/plain", "text": text}]}}

    if req.method == "prompts/list":
        return {"jsonrpc": "2.0", "id": req.id, "result": {"prompts": PROMPTS}}

    if req.method == "prompts/get":
        name = params.get("name", "")
        args = params.get("arguments", {})
        if name == "support-reply-drafter":
            prompt_text = (
                f"Write a short, polite support reply.\n"
                f"Customer: {args.get('customer_name', '')}\n"
                f"Issue: {args.get('issue', '')}\n"
                f"Resolution: {args.get('resolution', '')}\n"
                f"Tone: empathetic, professional, under 120 words."
            )
        elif name == "refund-approval-explainer":
            prompt_text = (
                f"Explain this refund request to a human approver in 3 bullet points:\n"
                f"Order: {args.get('order_id', '')}\n"
                f"Amount: ₹{args.get('amount', '')}\n"
                f"Reason: {args.get('reason', '')}\n"
                f"Include one line about the risks of approving vs rejecting."
            )
        else:
            return {"jsonrpc": "2.0", "id": req.id, "result": {"isError": True}}
        return {"jsonrpc": "2.0", "id": req.id, "result": {
            "messages": [{"role": "user", "content": {"type": "text", "text": prompt_text}}]}}

    return {"jsonrpc": "2.0", "id": req.id, "error": {"code": -32601, "message": f"Method not found: {req.method}"}}


