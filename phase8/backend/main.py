# Consent / approval REST API (used by the frontend modal)
# ---------------------------------------------------------------------------
class ApprovalRequest(BaseModel):
    action: str = "process_refund"
    order_id: str
    amount: float
    reason: str


@app.post("/api/approvals", dependencies=[Depends(require_api_key)])
def request_approval(body: ApprovalRequest) -> dict:
    """Step 1 of the consent gate: a human must approve before the side effect runs."""
    order = next((o for o in ORDERS if o["id"] == body.order_id), None)
    if not order:
        raise HTTPException(404, f"Order {body.order_id} not found")
    customer = next(c for c in CUSTOMERS if c["id"] == order["customer_id"])
    summary = f"Refund ₹{body.amount:g} to {customer['name']} for order {body.order_id} ({order['item']}). Reason: {body.reason}"
    approval = create_approval(body.action, body.model_dump(), summary)
    return approval


class ApprovalDecision(BaseModel):
    note: str = ""


@app.post("/api/approvals/{approval_id}/approve", dependencies=[Depends(require_api_key)])
def approve_and_execute(approval_id: str, body: ApprovalDecision) -> dict:
    """Step 2: human consented -> execute the side-effecting MCP tool once."""
    approval = APPROVALS.get(approval_id)
    if not approval:
        raise HTTPException(404, "Approval not found")
    if approval["status"] != "pending":
        raise HTTPException(409, f"Approval already {approval['status']}")
    approval["status"] = "approved"  # unlock the tool for one call
    params = dict(approval["params"])
    params["approval_id"] = approval_id
    outcome = call_tool(approval["action"], params)
    approval["note"] = body.note
    if not outcome["ok"]:
        approval["status"] = "rejected"  # tool refused: roll the gate back
        raise HTTPException(422, outcome["error"])
    return {"approval": approval, "result": outcome["result"]}


@app.post("/api/approvals/{approval_id}/reject", dependencies=[Depends(require_api_key)])
def reject_approval(approval_id: str, body: ApprovalDecision) -> dict:
    approval = APPROVALS.get(approval_id)
    if not approval:
        raise HTTPException(404, "Approval not found")
    approval["status"] = "rejected"
    approval["note"] = body.note
    return approval


@app.get("/api/approvals", dependencies=[Depends(require_api_key)])
def list_approvals() -> list[dict]:
    return list(APPROVALS.values())


