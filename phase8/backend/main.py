# The assistant — routes user text to MCP tools, then (optionally) phrases
# the answer with the configured AI service.
# ---------------------------------------------------------------------------
class ChatRequest(BaseModel):
    message: str


async def ask_ai(user_message: str, tool_context: str) -> Optional[str]:
    """Call the configured OpenAI-compatible chat endpoint. None if unavailable."""
    if not AI_API_KEY:
        return None
    system = (
        "You are BusinessOps Assistant, a friendly support assistant for a small electronics store. "
        "You can search customers, read orders, create support tickets, and process refunds (with human approval). "
        "Keep answers short (under 100 words). Tool data:\n" + tool_context
    )
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            resp = await client.post(
                f"{AI_BASE_URL}/chat/completions",
                headers={"Authorization": f"Bearer {AI_API_KEY}", "Content-Type": "application/json"},
                json={"model": AI_MODEL, "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user_message},
                ]},
            )
            resp.raise_for_status()
            return resp.json()["choices"][0]["message"]["content"]
    except Exception:
        return None  # fall back to built-in reply so the demo never breaks


def extract_name(text: str) -> Optional[str]:
    """Best-effort: pull 'for X' / 'of X' / 'customer X' out of a message."""
    m = re.search(r"(?:for|of|customer)\s+([A-Za-z]+)", text, re.IGNORECASE)
    return m.group(1) if m else None


@app.post("/api/chat", dependencies=[Depends(require_api_key)])
async def chat(body: ChatRequest) -> dict:
    msg = body.message.strip()
    lower = msg.lower()
    tool_context = ""

    # --- Intent 1: refund (the guarded side effect) -------------------------
    if "refund" in lower:
        m = re.search(r"ord-\d+", lower)
        amt = re.search(r"₹?\s*(\d+(?:\.\d+)?)", msg)
        order_id = m.group(0).upper() if m else None
        amount = float(amt.group(1)) if amt else None
        if not order_id or amount is None:
            text = ("To process a refund, tell me: order ID and amount.\n"
                    "Example: *refund ₹500 for ORD-1008 because item was damaged*\n"
                    "You will be asked to approve it before any money moves.")
            ai = await ask_ai(msg, text)
            return {"type": "message", "text": ai or text}
        reason = msg.split("because")[-1].strip() if "because" in lower else "requested by customer"
        approval = request_approval(ApprovalRequest(order_id=order_id, amount=amount, reason=reason))
        return {"type": "approval_required", "approval": approval,
                "text": f"I've prepared a refund of ₹{amount:g} for {order_id}. Please review and approve it below."}

    # --- Intent 2: create a support ticket ----------------------------------
    if "ticket" in lower and any(w in lower for w in ("create", "raise", "file", "open")):
        name = extract_name(msg)
        matches = find_customer(name) if name else []
        if not matches:
            text = ("Sure — which customer is the ticket for?\n"
                    "Example: *create ticket for Priya about laptop stand is broken, priority high*")
            return {"type": "message", "text": text}
        priority = "high" if "high" in lower else "low" if "low" in lower else "medium"
        about = re.sub(r"(?i)create ticket for \w+ (about|regarding)?\s*", "", msg).strip()
        outcome = call_tool("create_support_ticket", {
            "customer_id": matches[0]["id"], "subject": about[:80] or "General issue",
            "description": about or "No details provided.", "priority": priority})
        ticket = outcome["result"]
        tool_context = json.dumps(ticket)
        text = (f"Ticket {ticket['id']} created for {matches[0]['name']} ✅\n"
                f"Subject: {ticket['subject']}\nPriority: {ticket['priority']}")
        ai = await ask_ai(msg, tool_context)
        return {"type": "message", "text": ai or text}

    # --- Intent 3: read orders ----------------------------------------------
    if "order" in lower and any(w in lower for w in ("show", "list", "read", "get", "what")):
        name = extract_name(msg)
        matches = find_customer(name) if name else []
        if not matches:
            text = "Whose orders should I look up? Example: *show orders of Priya*"
            return {"type": "message", "text": text}
        rows = orders_of_any([c["id"] for c in matches])
        tool_context = json.dumps(rows)
        if not rows:
            text = f"No orders found for {matches[0]['name']}."
        else:
            lines = [f"• {o['id']} — {o['item']} — ₹{o['amount']:,} — {o['status']} ({o['date']})" for o in rows]
            text = f"Orders of {matches[0]['name']}:\n" + "\n".join(lines)
        ai = await ask_ai(msg, tool_context)
        return {"type": "message", "text": ai or text}

    # --- Intent 4: search customers ------------------------------------------
    if any(w in lower for w in ("customer", "search", "find", "who is")):
        name = extract_name(msg) or re.sub(r"(?i)(search|find|customer|for|who is)\s*", "", msg).strip()
        matches = find_customer(name) if name else []
        tool_context = json.dumps(matches)
        if not matches:
            text = f"No customer matched '{name}'. Try a name, city or email."
        else:
            lines = [f"• {c['id']} — {c['name']} ({c['tier']}) — {c['city']} — {c['email']}" for c in matches]
            text = f"Found {len(matches)} customer(s):\n" + "\n".join(lines)
        ai = await ask_ai(msg, tool_context)
        return {"type": "message", "text": ai or text}

    # --- Fallback: general question / help ------------------------------------
    help_text = ("I can help with:\n"
                 "• *find customer Priya*\n"
                 "• *show orders of Rohan*\n"
                 "• *create ticket for Aarav about mouse not working, priority high*\n"
                 "• *refund ₹500 for ORD-1008 because item was damaged* (needs your approval)")
    tool_context = json.dumps(store_summary())
    ai = await ask_ai(msg, tool_context)
    return {"type": "message", "text": ai or help_text}
